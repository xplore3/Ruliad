/**
 * 更新地推评分规则：
 * 1. 地推销售忌讳新增第九条：免费送邀请函扣5分。
 * 2. 地推主动性补充快速筛选推进的业务逻辑与具体改进建议要求。
 * 用法：DATABASE_URL="file:<绝对路径>/prisma/dev.db" node update-ground-push-rules.mjs
 */
import { PrismaClient } from '@prisma/client';
const prisma = new PrismaClient();

// ── 1. 地推销售忌讳：新增送邀请函扣5分 ──
const taboo = await prisma.scoreItemDef.findFirst({ where: { name: '地推销售忌讳' } });
if (taboo) {
  const data = JSON.parse(taboo.data);
  if (!data.behaviorAnchor.includes('送邀请函')) {
    data.behaviorAnchor += '\n9. 邀请函是现场筛选意向和推进成交的工具，不能免费送给客户。销售主动提出送邀请函、免费让客户拿走或不收钱直接给，整场最终总分扣5分，同一场不重复累计。应坚持现场售卖，例如“这张邀请函5元，您现在给孩子订一张”。';
    data.judgePrompt += '\n第九条：销售主动把本应收费的邀请函免费送给客户、让客户免费拿走或不收钱直接给，扣5分，同一场不重复累计。邀请函是现场筛选意向和推进成交的工具，不能赠送；应坚持现场售卖。你的score和dimensions只评前三条，不得自行加入第九条分数，避免重复扣分。';
    await prisma.scoreItemDef.update({ where: { id: taboo.id }, data: { data: JSON.stringify(data) } });
    console.log('已更新「地推销售忌讳」：新增送邀请函扣5分');
  } else {
    console.log('「地推销售忌讳」已包含送邀请函规则，跳过');
  }
}

// ── 2. 地推主动性：补充快速筛选推进逻辑 ──
const initiative = await prisma.scoreItemDef.findFirst({ where: { name: '地推主动性' } });
if (initiative) {
  const data = JSON.parse(initiative.data);
  data.behaviorAnchor =
    '地推主动性总分100分，按销售实际行动分三部分评价。地推的核心是快速筛选和快速推进：学校放学只有几分钟，家长人群集中但时间窗口极短，销售必须迅速判断意向并推进成交，不能在无意向家长身上消耗时间，否则错失其他潜在家长。' +
    '1. 递邀请函快速筛选意向20分：告诉家长想邀请其参加试听活动，并明确让家长拿上邀请函，利用接卡反应筛选意向。只邀请不递卡不得分，客户自己拿卡但销售未引导也不得分。' +
    '2. 介绍体验课和邀请函并主动售卖50分：家长拿上邀请函后，销售应立即介绍体验课内容和邀请函价值，并快速推进到现场售卖。完成必要介绍后，由销售主动引导客户购买邀请函，不能只介绍、答疑或等待客户推进。' +
    '3. 确定试听时间并填写用户信息30分：主动约定具体试听时间15分，主动引导填写姓名、电话等用户信息15分。客户主动提出试听、约定或提供信息不能代替销售得分。' +
    '若最后机会后仍无实质推进，本项直接0分且本场未完成。';
  data.judgePrompt =
    '只评价地推主动推进，score按以下固定结构直接累加，最高100分。' +
    'A. 递邀请函筛选20分：学员说明试听邀请并明确让家长拿上或接过邀请函才得20；只有活动邀请没有递卡动作、客户自己拿卡或完全没有，均得0。' +
    'B. 介绍并售卖邀请函50分：家长拿上邀请函后，学员介绍体验课和邀请函，并主动明确要求客户购买、订下邀请函得50；只有介绍、价格解释、空泛邀请或等待客户表态，未主动提出购买，得0；如果已有明确售卖意图但行动不够完整，最多给25，必须说明依据。' +
    'C. 确定试听时间并填写用户信息30分：学员主动约定具体试听时间得15，主动引导填写姓名、电话等用户信息得15，两项都有得30；客户主动提出不能算学员得分。' +
    '客户的中性回应、客户主动问试听流程或下一步均不得给学员加分。score=A+B+C的整数总分，rationale必须按A/B/C逐项列出得分并引用学员原话，不能只凭热情打分。' +
    'betterScript必须具体说明地推要快速筛选和推进的原因：学校放学只有几分钟，家长人群集中但时间窗口极短，销售必须迅速判断意向并推进成交，不能在无意向家长身上消耗时间，否则错失其他潜在家长。' +
    '话术示范优先补齐缺失动作：“来，您拿上邀请函，我给您介绍一下体验课。这张邀请函5元，您现在给孩子订一张，在这边填下姓名和电话，我们把试听定在周六上午十点。”' +
    '若客户已给最后机会仍无实质推进，直接score=0并说明本场未完成。';
  await prisma.scoreItemDef.update({ where: { id: initiative.id }, data: { data: JSON.stringify(data) } });
  console.log('已更新「地推主动性」：写入快速筛选推进逻辑与改进建议要求');
}

await prisma.$disconnect();
